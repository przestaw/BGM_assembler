class TestAlignMaps:
    def test_align_2_binmaps_1(self):
        map1 = CppBinaryMap('one',
                            '00100111')
        map2 = CppBinaryMap('two',
                            '11100100')

        result = plot2bitmaps(map1, map2, h=2)

        expect = [[1., 1., 1., 0.16, 0.16, 0.68, 0.16, 0.16, 0.68, 0.68, 0.68],
                  [1., 1., 1., 0.16, 0.16, 0.68, 0.16, 0.16, 0.68, 0.68, 0.68],
                  [0.68, 0.68, 0.68, 0.16, 0.16, 0.68, 0.16, 0.16, 1., 1., 1.],
                  [0.68, 0.68, 0.68, 0.16, 0.16, 0.68, 0.16, 0.16, 1., 1., 1.],
                  [1., 1., 1., 0.45, 0.45, 0.45, 0.45, 0.45, 1., 1., 1.],
                  [1., 1., 1., 0.45, 0.45, 0.45, 0.45, 0.45, 1., 1., 1.]]

        for i in range(0, 5):
            for j in range(0, 10):
                assert np.isclose(result[i][j], expect[i][j])

